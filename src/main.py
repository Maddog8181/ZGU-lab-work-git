def add(a, b):
    """Возвращает сумму двух чисел."""
    return a + b


def multiply(a, b):
    """Возвращает произведение двух чисел."""
    return a * b


def main():
    print("Учебный калькулятор: сложение и умножение.")
    print("2 + 3 =", add(2, 3))
    print("2 * 3 =", multiply(2, 3))


if __name__ == "__main__":
    main()
